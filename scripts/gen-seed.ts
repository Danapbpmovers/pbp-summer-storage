// Regenerates supabase/migrations/0002_seed.sql from src/data/seed.ts.
// Run: npm run gen:seed
import { writeFileSync } from 'node:fs'
import { buSeed, otherCampuses } from '../src/data/seed.ts'

const q = (v: unknown): string =>
  v === null || v === undefined
    ? 'null'
    : typeof v === 'number' || typeof v === 'boolean'
      ? String(v)
      : Array.isArray(v)
        ? `array[${v.map(q).join(',')}]::text[]`
        : `'${String(v).replace(/'/g, "''")}'`

const out: string[] = ['-- Generated by scripts/gen-seed.ts from src/data/seed.ts. Safe to re-run.', '']
const campusCols = ['slug', 'name', 'short_name', 'timezone', 'active', 'bookable', 'service_radius_miles', 'in_room_pickup',
  'official_partner_copy', 'official_partner_confirmed', 'seo_title', 'seo_description', 'sort'] as const

out.push(`insert into public.campuses (${campusCols.join(', ')}) values`)
out.push([buSeed.campus, ...otherCampuses].map((c) => `  (${campusCols.map((k) => q(c[k])).join(', ')})`).join(',\n'))
out.push('on conflict (slug) do nothing;', '')

const bu = `(select id from public.campuses where slug = '${buSeed.campus.slug}')`

out.push('do $$ begin', `if not exists (select 1 from public.catalog_items where campus_id = ${bu}) then`)
out.push('insert into public.catalog_items (campus_id, category, name, price_cents, note, service_types, sort) values')
out.push(buSeed.catalog.map((i) => `  (${bu}, ${q(i.category)}, ${q(i.name)}, ${i.price_cents}, ${q(i.note)}, ${q(i.service_types)}, ${i.sort})`).join(',\n') + ';')
out.push('insert into public.locations (campus_id, type, name, address, sort) values')
out.push(buSeed.locations.map((l, i) => `  (${bu}, ${q(l.type)}, ${q(l.name)}, ${q(l.address)}, ${i})`).join(',\n') + ';')
out.push('end if; end $$;', '')

out.push('insert into public.fee_rules (campus_id, code, name, amount_cents, unit, note, sort) values')
out.push(buSeed.fees.map((f, i) => `  (${bu}, ${q(f.code)}, ${q(f.name)}, ${f.amount_cents}, ${q(f.unit)}, ${q(f.note)}, ${i})`).join(',\n'))
out.push('on conflict (campus_id, code) do nothing;', '')

const ins = buSeed.insurance
out.push('insert into public.insurance_plans (campus_id, included_cents, addon_cents_per_100, max_per_box_cents, max_per_order_cents, claim_window_days) values')
out.push(`  (${bu}, ${ins.included_cents}, ${ins.addon_cents_per_100}, ${q(ins.max_per_box_cents)}, ${q(ins.max_per_order_cents)}, ${ins.claim_window_days})`)
out.push('on conflict (campus_id) do nothing;', '')

out.push('insert into public.calendar_windows (campus_id, key, label, starts_on, ends_on) values')
out.push(buSeed.calendar.map((c) => `  (${bu}, ${q(c.key)}, ${q(c.label)}, ${q(c.starts_on)}, ${q(c.ends_on)})`).join(',\n'))
out.push('on conflict (campus_id, key) do nothing;', '')

out.push('insert into public.station_hours (campus_id, date, hours) values')
out.push(buSeed.station_hours.map((h) => `  (${bu}, ${q(h.date)}, ${q(h.hours)})`).join(',\n'))
out.push('on conflict (campus_id, date) do nothing;', '')

out.push(
  '-- Default capacity: 120 drop-offs per station per day during move-out stations,',
  '-- and 40 curbside pickups per window. Adjust in /admin/calendar.',
  'insert into public.slots (campus_id, location_id, kind, date, window_label, capacity)',
  `select l.campus_id, l.id, 'station_dropoff', h.date, h.hours, 120`,
  '  from public.locations l join public.station_hours h on h.campus_id = l.campus_id',
  ` where l.type in ('move_out_station', 'store') and l.campus_id = ${bu}`,
  '   and not exists (select 1 from public.slots s where s.location_id = l.id and s.date = h.date);',
  'insert into public.slots (campus_id, kind, date, window_label, capacity)',
  `select ${bu}, 'curbside_pickup', d::date, w, 40`,
  "  from generate_series('2027-05-01'::date, '2027-05-09'::date, '1 day') d, unnest(array['9am – 12pm', '12pm – 3pm', '3pm – 6pm']) w",
  ` where not exists (select 1 from public.slots s where s.campus_id = ${bu} and s.kind = 'curbside_pickup' and s.date = d::date and s.window_label = w);`,
  '',
  '-- After you sign up, make yourself an admin:',
  "-- update public.profiles set role = 'admin' where email = 'you@example.com';",
  '',
)

writeFileSync(new URL('../supabase/migrations/0002_seed.sql', import.meta.url), out.join('\n'))
console.log('wrote supabase/migrations/0002_seed.sql')
